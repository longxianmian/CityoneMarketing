type MessageSchema = typeof messages.zh

type I18nContextValue = {
  language: AppLanguage
  languageMode: LanguageMode
  setLanguage: (lang: AppLanguage) => void
  setAutoLanguage: () => void
  t: (path: string) => string
  antdLocale: Locale
}

const I18nContext = createContext<I18nContextValue | null>(null)

function getAntdLocale(lang: AppLanguage): Locale {
  if (lang === 'zh') return zhCN
  if (lang === 'th') return thTH
  return enUS
}

function getMessage(lang: AppLanguage, path: string): string {
  const parts = path.split('.')
  let current: any = messages[lang]

  for (const key of parts) {
    current = current?.[key]
  }

  if (typeof current === 'string') return current

  const fallbackParts = path.split('.')
  let fallback: any = messages.en
  for (const key of fallbackParts) {
    fallback = fallback?.[key]
  }
  return typeof fallback === 'string' ? fallback : path
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [languageMode, setLanguageModeState] = useState<LanguageMode>(detectInitialLanguageMode())
  const [language, setLanguageState] = useState<AppLanguage>(detectInitialLanguage())

  useEffect(() => {
    if (languageMode === 'auto') {
      const next = detectBrowserLanguage()
      if (next !== language) {
        setLanguageState(next)
      }
      localStorage.setItem(STORAGE_MODE_KEY, 'auto')
      localStorage.removeItem(STORAGE_KEY)
    } else {
      localStorage.setItem(STORAGE_MODE_KEY, 'manual')
      localStorage.setItem(STORAGE_KEY, language)
    }

    document.documentElement.lang = language
  }, [language, languageMode])

  useEffect(() => {
    if (languageMode !== 'auto') return

    const syncBrowserLanguage = () => {
      const next = detectBrowserLanguage()
      setLanguageState((prev) => (prev === next ? prev : next))
    }

    window.addEventListener('focus', syncBrowserLanguage)
    document.addEventListener('visibilitychange', syncBrowserLanguage)

    return () => {
      window.removeEventListener('focus', syncBrowserLanguage)
      document.removeEventListener('visibilitychange', syncBrowserLanguage)
    }
  }, [languageMode])

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      languageMode,
      setLanguage: (lang) => {
        setLanguageModeState('manual')
        setLanguageState(lang)
      },
      setAutoLanguage: () => {
        setLanguageModeState('auto')
        setLanguageState(detectBrowserLanguage())
      },
      t: (path) => getMessage(language, path),
      antdLocale: getAntdLocale(language),
    }),
    [language, languageMode]
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) {
    throw new Error('useI18n must be used within I18nProvider')
  }
  return ctx
}

/**
 * 动态内容三语读取工具：
 * content = {
 *   title: { zh: '标题', th: 'ชื่อ', en: 'Title' }
 * }
 */
export function pickLocalizedText(
  content: Record<string, Partial<Record<AppLanguage, string>> | undefined>,
  field: string,
  lang: AppLanguage
): string {
  const item = content[field]
  if (!item) return ''
  return item[lang] || item.en || item.zh || item.th || ''
}
