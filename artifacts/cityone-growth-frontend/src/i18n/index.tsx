export type AppLanguage = 'zh' | 'th' | 'en'
export type LanguageMode = 'auto' | 'manual'

const STORAGE_KEY = 'cityone_growth_lang'
const STORAGE_MODE_KEY = 'cityone_growth_lang_mode'

function normalizeLanguage(input?: string | null): AppLanguage {
  const raw = (input || '').toLowerCase()
  if (raw.startsWith('zh')) return 'zh'
  if (raw.startsWith('th')) return 'th'
  if (raw.startsWith('en')) return 'en'
  return 'en'
}

function detectBrowserLanguage(): AppLanguage {
  const browserLang =
    typeof navigator !== 'undefined'
      ? navigator.language || (Array.isArray(navigator.languages) ? navigator.languages[0] : 'en')
      : 'en'

  return normalizeLanguage(browserLang)
}

export function detectInitialLanguageMode(): LanguageMode {
  const savedMode = typeof window !== 'undefined' ? window.localStorage.getItem(STORAGE_MODE_KEY) : null
  return savedMode === 'manual' ? 'manual' : 'auto'
}

export function detectInitialLanguage(): AppLanguage {
  const mode = detectInitialLanguageMode()

  if (mode === 'manual') {
    const saved = typeof window !== 'undefined' ? window.localStorage.getItem(STORAGE_KEY) : null
    if (saved) return normalizeLanguage(saved)
  }

  return detectBrowserLanguage()
}

